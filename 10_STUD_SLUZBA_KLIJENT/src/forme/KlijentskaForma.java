    private void jButtonUnesiProfActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonUnesiProfActionPerformed
        String ime = jTextFieldIme.getText();
        String prezime = jTextFieldPrezime.getText();
        Zvanje zvanje = Zvanje.valueOf((String) jComboBoxZvanje.getSelectedItem());

        p = new Profesor(-1, ime, prezime, zvanje, k.getEmail());

        KlijentskiZahtev kz = new KlijentskiZahtev(Operacije.UNESI_PROF, p);
        Komunikacija.getInstance().posaljiZahtev(kz);

        ServerskiOdgovor so = Komunikacija.getInstance().primiOdgovor();
        p = (Profesor) so.getOdgovor();

        if (p == null) {
            JOptionPane.showMessageDialog(null, "GRESKA");
        } else {
            popuniTabelu();
            JOptionPane.showMessageDialog(null, "USPEH");
        }

    }//GEN-LAST:event_jButtonUnesiProfActionPerformed

    private void jButtonUnesiPredActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonUnesiPredActionPerformed
        String naziv = jTextFieldNaziv.getText();
        String kod = jTextFieldKod.getText();
        int esp = Integer.parseInt(jTextFieldEsp.getText());

        Predmet pred = new Predmet(-1, naziv, kod, esp);

        KlijentskiZahtev kz = new KlijentskiZahtev(Operacije.UNESI_PRED, pred);
        Komunikacija.getInstance().posaljiZahtev(kz);

        ServerskiOdgovor so = Komunikacija.getInstance().primiOdgovor();
        boolean uspeh = (boolean) so.getOdgovor();

        if (uspeh) {
            JOptionPane.showMessageDialog(null, "USPEH");
        } else {
            JOptionPane.showMessageDialog(null, "GRESKA");
        }


    }//GEN-LAST:event_jButtonUnesiPredActionPerformed

    private void jButtonUnosActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonUnosActionPerformed
        int selektovaniRed = jTableProfesori.getSelectedRow();
        if(selektovaniRed == -1){
            JOptionPane.showMessageDialog(null, "MORATE IZABRATI RED");
        }else{
            ModelTabeleProfesor mtp = (ModelTabeleProfesor) jTableProfesori.getModel();
            Profesor prof = mtp.getLista().get(selektovaniRed);
            
            UnosAngazovanjaForma uaf = new UnosAngazovanjaForma(this, false, prof, k);
            uaf.setVisible(true);
            
        }
    }//GEN-LAST:event_jButtonUnosActionPerformed


