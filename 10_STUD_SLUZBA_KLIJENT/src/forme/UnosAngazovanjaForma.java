    private void jButtonUnosAngActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonUnosAngActionPerformed

        ModelTabeleAngazovanja mta = (ModelTabeleAngazovanja) jTableAngazovanja.getModel();

        if (mta.getLista().size() >= 3) {
            JOptionPane.showMessageDialog(null, "VEC IMA 3 ANGAZOVANJA");
            return;
        }

        Date datum = new Date();
        Predmet pred = (Predmet) jComboBoxPredmet.getSelectedItem();
        String email = k.getEmail();

        Angazovanje a = new Angazovanje(-1, datum, p, pred, email);

        mta.dodaj(a);


    }//GEN-LAST:event_jButtonUnosAngActionPerformed

    private void jButtonObrisiActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonObrisiActionPerformed
        int selektovaniRed = jTableAngazovanja.getSelectedRow();
        if(selektovaniRed == -1){
            JOptionPane.showMessageDialog(null, "MORAS DA SELEKTUJES RED");
        }else{
            ModelTabeleAngazovanja mta = (ModelTabeleAngazovanja) jTableAngazovanja.getModel();
            mta.obrisi(selektovaniRed);
        }
    }//GEN-LAST:event_jButtonObrisiActionPerformed

    private void jButtonSacuvajActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonSacuvajActionPerformed
        ModelTabeleAngazovanja mta = (ModelTabeleAngazovanja) jTableAngazovanja.getModel();
        List<Angazovanje> lista = mta.getLista();
        
        KlijentskiZahtev kz = new KlijentskiZahtev(Operacije.SACUVAJ_ANG, lista);
        Komunikacija.getInstance().posaljiZahtev(kz);
        
        ServerskiOdgovor so = Komunikacija.getInstance().primiOdgovor();
        boolean uspeh = (boolean) so.getOdgovor();
        
        if(uspeh){
            JOptionPane.showMessageDialog(null, "USPESNO AZURIRANO");
            popuniTabelu();
        }else{
            JOptionPane.showMessageDialog(null, "GRESKA");
        }
        
        
        
    }//GEN-LAST:event_jButtonSacuvajActionPerformed

    private void jButtonAzurirajActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonAzurirajActionPerformed
        int selektovaniRed = jTableAngazovanja.getSelectedRow();
        if(selektovaniRed == -1){
            JOptionPane.showMessageDialog(null, "MORAS DA SELEKTUJES RED");
        }else{
            ModelTabeleAngazovanja mta = (ModelTabeleAngazovanja) jTableAngazovanja.getModel();
            Angazovanje a = mta.getLista().get(selektovaniRed);
            AzurirajAngazovanje aa = new AzurirajAngazovanje(this, false, a);
            aa.setVisible(true);
            
            mta.osveziTabelu();
        }
    }//GEN-LAST:event_jButtonAzurirajActionPerformed


