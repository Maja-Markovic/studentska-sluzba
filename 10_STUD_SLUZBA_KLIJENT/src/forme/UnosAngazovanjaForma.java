    private void popuniComboBoxPredmet() {
        jComboBoxPredmet.removeAllItems();

        KlijentskiZahtev kz = new KlijentskiZahtev(Operacije.UCITAJ_PRED, null);
        Komunikacija.getInstance().posaljiZahtev(kz);

        ServerskiOdgovor so = Komunikacija.getInstance().primiOdgovor();
        List<Predmet> predmeti = (List<Predmet>) so.getOdgovor();

        for (Predmet predmet : predmeti) {
            jComboBoxPredmet.addItem(predmet);
        }

    }

    private void popuniTabelu() {

        KlijentskiZahtev kz = new KlijentskiZahtev(Operacije.UCITAJ_ANG, p);
        Komunikacija.getInstance().posaljiZahtev(kz);

        ServerskiOdgovor so = Komunikacija.getInstance().primiOdgovor();
        List<Angazovanje> ang = (List<Angazovanje>) so.getOdgovor();

        ModelTabeleAngazovanja mta = new ModelTabeleAngazovanja(ang);
        jTableAngazovanja.setModel(mta);

    }

    void azurirajDatum(Angazovanje a) {
        ModelTabeleAngazovanja mta= (ModelTabeleAngazovanja) jTableAngazovanja.getModel();
        mta.azuriraj(a);
    }

    
